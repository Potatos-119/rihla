export type Interest =
  | 'heritage'
  | 'food'
  | 'nature'
  | 'modern'
  | 'family'
  | 'shopping'
  | 'sea'
  | 'crafts'

export type Meal = 'breakfast' | 'lunch' | 'dinner'

/** A price range in Bahraini dinars: [low, high]. */
export type Range = [number, number]

export interface PlaceData {
  id: string
  name: string
  arabic: string
  area: string
  lat: number
  lng: number
  tags: Interest[]
  /** typical visit length in minutes */
  minutes: number
  /** 0–5, how strongly we'd recommend it to a first-time visitor */
  rating: number
  open: string
  close: string
  /** days the place is closed, 0 = Sunday … 6 = Saturday */
  closedDays?: number[]
  /** different hours on some weekdays (e.g. Friday afternoons only); null means closed */
  hours?: Partial<Record<number, [string, string] | null>>
  /** food places that suit a meal slot */
  meals?: Meal[]
  outdoor?: boolean
  /** best enjoyed around sunset */
  sunset?: boolean
  blurb: string
  tip: string
  /** entry fee per person in BD; omitted means free */
  entry?: { adult: Range; child: Range }
  /** typical food spend per adult in BD, per meal slot */
  spend?: Partial<Record<Meal, Range>>
  /** a paid activity that is the point of the visit (e.g. karting) */
  extra?: { label: string; adult: Range; child: Range }
  priceNote?: string
  hoursNote?: string
  /** something a visitor must know before going */
  notice?: string
  /** which facts could not be confirmed from a reliable source */
  approx?: ('price' | 'hours' | 'coords')[]
  /** where the facts were checked, and when (YYYY-MM-DD) */
  source: string
  checked: string
}

export interface Place extends PlaceData {
  /** coarse tier derived from the real prices: 0 free · 1 under BD 3 · 2 BD 3–10 · 3 above BD 10 */
  cost: 0 | 1 | 2 | 3
}

