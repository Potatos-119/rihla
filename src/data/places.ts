function tier(p: PlaceData): Place['cost'] {
  const top = (p.entry?.adult[1] ?? 0) + (p.extra?.adult[1] ?? 0)
  return top === 0 ? 0 : top < 3 ? 1 : top <= 10 ? 2 : 3
}

