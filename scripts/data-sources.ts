// Writes docs/DATA-SOURCES.md from src/data/places.ts so the table never drifts from the data.
//   npm run sources
import { writeFileSync } from 'node:fs'
import { PLACES } from '../src/data/places'
import { formatRange } from '../src/lib/cost'
import { fmt, toMin, WEEKDAYS } from '../src/lib/planner'

const hours = (p: (typeof PLACES)[number]) =>
  (p.open === '00:00' && p.close === '23:59' ? 'Open all day' : `${fmt(toMin(p.open))}–${fmt(toMin(p.close))}`) +
  (p.closedDays?.length ? `, closed ${p.closedDays.map((d) => WEEKDAYS[d].slice(0, 3)).join('/')}` : '')

const price = (p: (typeof PLACES)[number]) => {
  const parts: string[] = []
  if (p.entry && p.entry.adult[1] > 0) parts.push(`Entry: adult ${formatRange(p.entry.adult)}, child ${formatRange(p.entry.child)}`)
  if (p.spend) parts.push(Object.entries(p.spend).map(([m, r]) => `${m} ${formatRange(r!)} pp`).join(', '))
  if (p.extra) parts.push(`${p.extra.label}: ${formatRange(p.extra.adult)} pp`)
  return parts.join('; ') || 'Free'
}

const host = (u: string) => new URL(u).hostname.replace(/^www\./, '')
const rows = PLACES.map(
  (p) =>
    `| ${p.name} | ${p.lat.toFixed(4)}, ${p.lng.toFixed(4)} | ${hours(p)} | ${price(p)} | ${p.approx?.join(', ') || '–'} | [${host(p.source)}](${p.source}) | ${p.checked} |`,
)

const md = `# Data sources

Every place in Rihla was checked on the date shown, against the source linked. Where reliable sources disagreed or no official figure exists, the field is marked **approximate**. The app shows it as approximate or as an estimate, rather than presenting a guess as fact.

Prices are in Bahraini dinars (BD). "pp" means a typical spend per adult; children are counted at 60% of an adult for food.

Map positions were cross-checked against OpenStreetMap (Nominatim) and Wikipedia coordinates.

| Place | Map position | Hours used for planning | Prices | Approximate | Source | Checked |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

_This file is generated by \`npm run sources\` from \`src/data/places.ts\`._
`

writeFileSync(new URL('../docs/DATA-SOURCES.md', import.meta.url), md)
console.log(`wrote ${PLACES.length} rows`)
